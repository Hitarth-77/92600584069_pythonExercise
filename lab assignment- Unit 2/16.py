# List
fruits = ["apple", "mango", "orange", "banana"]

print("List Elements:")
for fruit in fruits:
    print(fruit)


# String
name = "Python"

print("\nString Characters:")
for character in name:
    print(character)


# Dictionary
student = {
    "Name": "Hitarth",
    "Age": 21,
    "Course": "MCA"
}

print("\nDictionary Key and Values:")
for key, value in student.items():
    print(key, ":", value)
