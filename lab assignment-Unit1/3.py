# User-defined numbers
a = int(input("Enter first number: "))
b = int(input("Enter second number: "))
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# Relational Operators
print("a > b:", a > b)
print("a == b:", a == b)

# Logical Operators
print((a > b) and (b > 0))
print((a < b) or (b > 0))
print(not(a < b))